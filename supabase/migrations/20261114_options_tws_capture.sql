-- TWS capture (Nov 2026). The weekly review runs on Saturday, when TWS has usually
-- restarted and only holds the current session's executions. The Mac now copies every
-- TWS execution and a positions snapshot into Supabase each hour, so the review can
-- check every close against what TWS actually did (the QQQ 62 close on 11 Nov was
-- recorded at the exit plan's target prices with no TWS fill behind it).

-- One row per TWS execution (one leg of one fill). Upserted on exec_id, so re-running
-- the capture is harmless.
create table if not exists options.tws_executions (
  exec_id       text primary key,
  perm_id       text,                 -- same on every leg of one order: group combos on it
  order_id      text,
  order_ref     text,
  account       text,                 -- DU… = paper, U… = live
  mode          text,                 -- paper | live (from the bridge's /api/health)
  exec_time_raw text,                 -- exactly as TWS gave it
  exec_ts       timestamptz,          -- parsed, null if the format was not recognised
  ny_date       text,                 -- YYYY-MM-DD in New York
  symbol        text,
  sec_type      text,
  expiry        text,                 -- YYYYMMDD
  strike        numeric,
  "right"       text,                 -- C | P
  side          text,                 -- BOT | SLD
  qty           numeric,
  price         numeric,              -- per share, this leg
  avg_price     numeric,
  multiplier    numeric,
  commission    numeric,
  realized_pnl  numeric,
  captured_at   timestamptz not null default now(),
  raw           jsonb
);
create index if not exists tws_executions_day on options.tws_executions (ny_date, symbol);
create index if not exists tws_executions_perm on options.tws_executions (perm_id);

-- Option positions as TWS reports them. A new row only when the positions change.
create table if not exists options.tws_positions (
  id           bigint generated by default as identity primary key,
  captured_at  timestamptz not null default now(),
  account      text,
  mode         text,
  hash         text not null,         -- of the sorted legs; unchanged → no new row
  legs         jsonb not null,        -- [{ account, underlying, expiry, strike, right, qty, avgCost, multiplier }]
  structures   jsonb
);
create index if not exists tws_positions_time on options.tws_positions (captured_at desc);

-- Heartbeat: one row per capture attempt, so the review can tell "no trades" from
-- "the capture wasn't running".
create table if not exists options.tws_capture_runs (
  id           bigint generated by default as identity primary key,
  run_at       timestamptz not null default now(),
  ok           boolean not null,
  mode         text,
  accounts     text,
  executions   integer,
  new_executions integer,
  positions    integer,
  positions_changed boolean,
  error        text
);
create index if not exists tws_capture_runs_time on options.tws_capture_runs (run_at desc);

-- Audit trail for every correction the weekly review makes, with the old value, so
-- any change can be reverted by hand.
create table if not exists options.review_corrections (
  id           bigint generated by default as identity primary key,
  made_at      timestamptz not null default now(),
  review_week  text,                  -- w/e Friday, YYYY-MM-DD
  table_name   text not null,
  row_key      text not null,         -- e.g. close_id=C1794412632243 or row_no=62
  action       text not null,         -- update | insert | delete
  column_name  text,
  old_value    text,
  new_value    text,
  old_row      jsonb,                 -- full row before an update/delete
  evidence     text not null,         -- TWS exec ids / snapshot id it is based on
  reverted     boolean not null default false
);

-- Same as every other table in the schema: no access through the public API.
alter table options.tws_executions     enable row level security;
alter table options.tws_positions      enable row level security;
alter table options.tws_capture_runs   enable row level security;
alter table options.review_corrections enable row level security;
